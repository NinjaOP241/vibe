export type TodoStatus = "pending" | "in_progress" | "completed" | "cancelled";

export const statuses: readonly TodoStatus[] = [
  "pending",
  "in_progress",
  "completed",
  "cancelled",
];

export type TodoPhase = "design" | "build" | "review";

export type PhaseStatusAction = "start" | "complete" | "cancel";

const STATUS_FOR_PHASE_ACTION: Record<PhaseStatusAction, TodoStatus> = {
  start: "in_progress",
  complete: "completed",
  cancel: "cancelled",
} as const;

const PHASE_INDEX: Record<TodoPhase, number> = {
  design: 0,
  build: 1,
  review: 2,
};

// The planner must end each todo's content with an explicit phase tag.
const PHASE_TAG_PATTERN = /\bphase\s*:\s*(design|build|review)\s*\.?\s*$/i;

export function inferToDoPhase(content: string): TodoPhase {
  const match = content.match(PHASE_TAG_PATTERN);
  const phase = match?.[1]?.toLowerCase();

  if (phase === "design" || phase === "build" || phase === "review") {
    return phase;
  }

  throw new Error(`Todo content is missing a valid phase tag: "${content}"`);
}

/**
 * A record of valid status transitions for a todo item.
 * For example, a todo item can transition from "pending" to "in_progress",
 * but it cannot transition from "completed" to "in_progress".
 */
const STATUS_TRANSITIONS: Record<TodoStatus, TodoStatus[]> = {
  pending: ["in_progress", "completed", "cancelled"],
  in_progress: ["completed", "cancelled"],
  completed: [],
  cancelled: [],
};

/**
 * Checks if a transition from one status to another is valid based on the STATUS_TRANSITIONS map.
 * @param from The current status of the todo item.
 * @param to The desired status of the todo item.
 * @returns True if the transition is valid, false otherwise.
 */
export function canTransitionStatus(from: TodoStatus, to: TodoStatus): boolean {
  if (from === to) return true;
  return STATUS_TRANSITIONS[from].includes(to);
}

/**
 * Transitions a todo item from one status to another.
 * @param from The current status of the todo item.
 * @param to The desired status of the todo item.
 * @returns The new status of the todo item.
 */
export function transitionStatus(from: TodoStatus, to: TodoStatus): TodoStatus {
  if (canTransitionStatus(from, to)) {
    return to;
  }

  throw new Error(`Invalid status transition from "${from}" to "${to}".`);
}

/**
 * Updates the status of all todos in a given phase based on the specified action.
 * @param todos The list of todos to update.
 * @param phase The phase for which to update the todos.
 * @param action The action to perform on the todos in the specified phase.
 * @returns A new list of todos with updated statuses for the specified phase.
 */
export function updateTodoStatusForPhase(
  todos: TodoItem[],
  phase: TodoPhase,
  action: PhaseStatusAction,
): TodoItem[] {
  const nextStatus = STATUS_FOR_PHASE_ACTION[action];

  return todos.map((todo) => {
    if (todo.phase !== phase) {
      return todo;
    }

    return {
      ...todo,
      status: transitionStatus(todo.status, nextStatus),
    };
  });
}

export interface TodoItem {
  content: string;
  status: TodoStatus;
  phase: TodoPhase;
}

// For example: PLAN_KING = "plan" | "brief_plan" | "detailed_plan"
export const PLAN_KIND = "plan";

export interface PlanActivity {
  agent: string; // The agent that will perform the activity
  detail: string; // The details we are passing to the agent to perform the activity
}

/**
 * A plan generated by the planner agent needs to be stored inside the database
 * We will store the plan as a stringified version of this PlanMessage in the database
 */
export interface PlanMessage {
  todos: TodoItem[];
  kind: typeof PLAN_KIND;
  activity?: PlanActivity;
}

function isTodoStatus(value: unknown): value is TodoStatus {
  return (
    typeof value === "string" && (statuses as readonly string[]).includes(value)
  );
}

/**
 * Converts any messy json object into a clean TodoItem
 */
export function normalizeTodos(value: unknown): TodoItem | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return null;
  }

  const { content, status } = value as { content?: unknown; status?: unknown };

  if (typeof content !== "string" || !content.trim()) {
    return null;
  }

  let phase: TodoPhase;

  try {
    phase = inferToDoPhase(content);
  } catch {
    return null;
  }

  return {
    content: content.trim(),
    status: isTodoStatus(status) ? status : "pending",
    phase,
  };
}

/**
 * Converts a array of messy json objects into a clean array of TodoItems
 */
export function parsePlannerTodos(value: unknown): TodoItem[] {
  if (!Array.isArray(value)) {
    return [];
  }

  return value
    .map((item) => normalizeTodos(item))
    .filter((item): item is TodoItem => Boolean(item)); // Exclude null values from the result
}

/**
 * Converts a list of TodoItems into a formatted string that can be send to the agents
 * to have the context about the entire plan
 */
export function formatPlanForAgent(todos: TodoItem[]): string {
  const planLines = todos.map(
    (todo, index) => `${index + 1}. [${todo.status}] ${todo.content}`,
  );

  const footer =
    "Follow this plan in order. Update it with write_todos as you complete steps.";

  return ["Current plan:", ...planLines, "", footer].join("\n");
}

/**
 * parsePlanMessage() takes a string from a database message and
 * checks whether that string contains a saved plan.
 * If it does, it returns the plan’s todos as TodoItem[].
 * If the string is invalid JSON, is not marked as a plan, or
 * contains no valid todos, it returns null.
 *
 * For example, given this database message content:
 *  const content = `{
 *    "kind": "plan",
 *    "todos": [
 *      {
 *        "content": "Build the hero section. Phase: build",
 *        "status": "pending",
 *        "phase": "build"
 *      }
 *    ],
 *    "activity": {
 *      "agent": "planner",
 *      "detail": "Plan created"
 *    }
 *  }`;
 *
 * The function returns:
 *  [
 *    {
 *      content: "Build the hero section. Phase: build",
 *      status: "pending",
 *      phase: "build"
 *    }
 *  ]
 */
export function parsePlanMessage(content: string): TodoItem[] | null {
  let parsed: Partial<PlanMessage>;

  try {
    parsed = JSON.parse(content) as Partial<PlanMessage>;
  } catch {
    return null;
  }

  if (parsed.kind !== PLAN_KIND) {
    return null;
  }

  const todos = parsePlannerTodos(parsed.todos);

  return todos.length > 0 ? todos : null;
}

/**
 * serializePlanMessage() takes a list of TodoItems and an optional PlanActivity
 * and returns a stringified PlanMessage that can be stored in the database.
 */
export function serializePlanMessage(
  todos: TodoItem[],
  activity?: PlanActivity | null,
): string {
  const payload: PlanMessage = {
    todos,
    kind: PLAN_KIND,
  };

  if (activity) {
    payload.activity = activity;
  }

  return JSON.stringify(payload);
}

