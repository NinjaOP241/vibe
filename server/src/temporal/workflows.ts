import { proxyActivities } from "@temporalio/workflow";

import type * as activities from "./activities.js";

const { createSandbox, saveAssistantResult } = proxyActivities<
  typeof activities
>({
  startToCloseTimeout: "10 minutes",
  retry: {
    maximumAttempts: 3,
  },
});

export interface CodeAgentInput {
  projectId: string;
  userId: string;
  prompt: string;
}

export async function pingWorkflow(name: string): Promise<string> {
  return `Hello, ${name}! The ping workflow has been successfully executed.`;
}

export async function codeAgentWorkflow(input: CodeAgentInput) {
  // Create a sandbox for the project
  const sandboxId = await createSandbox({
    projectId: input.projectId,
    userId: input.userId,
  });

  // Save the dummy app result to the database
  await saveAssistantResult({
    isError: false,
    projectId: input.projectId,
    userId: input.userId,
    content: "This is a dummy response generated by the code agent.",
    title: "My Demo App",
    sandboxUrl: "https://example.com",
    files: {
      "src/App.tsx": `export default function App() {
        return <div>Hello, World!</div>;
      }`,
    },
  });

  return {
    files: null,
  };
}
